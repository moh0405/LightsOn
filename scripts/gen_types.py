"""Emit apps/web/src/lib/types.ts from server/app/models.py (Pydantic v2)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))

from app import models  # noqa: E402
from pydantic import BaseModel  # noqa: E402

OUT = ROOT / "apps/web/src/lib/types.ts"


def ts_type(s: dict, defs: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(f'"{v}"' for v in s["enum"])
    if "const" in s:
        return f'"{s["const"]}"'
    if "anyOf" in s:
        parts = list(dict.fromkeys(ts_type(x, defs) for x in s["anyOf"]))
        return " | ".join(parts)
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}), defs)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap, defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def main() -> None:
    lines = ["// GENERATED by scripts/gen_types.py from server/app/models.py. Do not edit.", ""]
    for name in ("Phase", "Category"):
        vals = getattr(models, name).__args__
        lines.append(f"export type {name} = " + " | ".join(f'"{v}"' for v in vals) + ";")
    lines.append("")
    for name, cls in vars(models).items():
        if not (isinstance(cls, type) and issubclass(cls, BaseModel) and cls is not BaseModel):
            continue
        schema = cls.model_json_schema()
        defs = schema.get("$defs", {})
        req = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for prop, ps in schema["properties"].items():
            t = ts_type(ps, defs)
            # Literal aliases inline as enums in Pydantic; map category/phase fields back to the alias
            if prop in ("category", "category_guess"):
                t = "Category"
            opt = "" if prop in req else "?"
            lines.append(f"  {prop}{opt}: {t};")
        lines.append("}")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
